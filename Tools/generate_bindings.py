#!/usr/bin/env python3
"""
generate_bindings.py — Pipeline de Automação de Bindings do Dofus Unity (Pilar 2)

Lê Decompiled/dump.cs gerado pelo Il2CppDumper, extrai as structs de binding
oficiais em Core.UILogic.Bindings, traduz os tipos proprietários da Ankama
para tipos padrão do Unity UI Toolkit e gera classes C# fortemente tipadas.
"""

import os
import re
import sys
from typing import Dict, List, Tuple

# Mapeamento oficial de tipos Ankama -> Unity UI Toolkit (Pilar 2 Lacuna 5)
TYPE_MAPPING: Dict[str, str] = {
    "DofusVisualElement": "VisualElement",
    "DofusLabel": "Label",
    "DofusButtonCustom": "Button",
    "DofusIcon": "VisualElement",
    "PlayButton": "VisualElement",
    "ServerCard": "VisualElement",
    "CheckboxCustom": "Toggle",
    "DofusTab": "VisualElement",
    "TextInput": "TextField",
    "TableColumnHeader": "VisualElement",
    "DofusToggleButtonCustom": "Toggle",
    "DofusToggleButtonGroupCustom": "VisualElement",
    "DropdownButton": "VisualElement",
    "EntityDisplayer": "VisualElement",
    "ListView": "ListView",
    "ScrollView": "ScrollView",
    "VisualElement": "VisualElement",
    "Label": "Label",
    "Button": "Button",
    "Toggle": "Toggle",
    "TextField": "TextField",
}

# As 8 structs oficiais de UI identificadas na auditoria (Pilar 2 Lacuna 6)
DEFAULT_TARGET_BINDINGS = [
    "LoginBinding",
    "ServerSelectionBinding",
    "CharacterSelectionBinding",
    "CharacterHeaderBinding",
    "ActionBarBinding",
    "BannerMenuBinding",
    "CharacterInformationsBinding",
    "ChatviewBinding",
]


def map_type(raw_type: str) -> str:
    """Mapeia um tipo Ankama para um tipo do Unity UI Toolkit. Se desconhecido, faz fallback seguro para VisualElement."""
    return TYPE_MAPPING.get(raw_type.strip(), "VisualElement")


def extract_fields_from_struct_text(struct_text: str) -> List[Tuple[str, str, str]]:
    """
    Extrai campos de um snippet de struct do dump.cs.
    Retorna lista de tuplas: (raw_type, mapped_type, clean_name).
    """
    fields = []
    # Regex para capturar linhas de campo: private Type _name; // offset
    field_pattern = re.compile(r"^\s*(?:private|public|internal)\s+([A-Za-z0-9_<>]+)\s+_([A-Za-z0-9_]+)\s*;", re.MULTILINE)
    
    for match in field_pattern.finditer(struct_text):
        raw_type = match.group(1)
        name = match.group(2)
        
        # Ignorar campos internos do compilador ou ponteiro root duplicado
        if name.startswith("____") or "<" in name or name == "root":
            continue
            
        mapped = map_type(raw_type)
        fields.append((raw_type, mapped, name))
        
    return fields


def parse_binding_from_dump(dump_text: str, binding_name: str) -> List[Tuple[str, str, str]]:
    """Localiza uma struct no dump.cs e extrai seus campos."""
    # Procura declaração: public struct BindingName : ... { ... }
    pattern = re.compile(rf"public\s+struct\s+{re.escape(binding_name)}\s*:[^{{]+\{{(.*?)(?=\n\s*//\s*(?:Properties|Methods)|\n\}})", re.DOTALL)
    match = pattern.search(dump_text)
    if not match:
        # Fallback para class se a Ankama tiver declarado como class
        pattern_class = re.compile(rf"public\s+class\s+{re.escape(binding_name)}\s*:[^{{]+\{{(.*?)(?=\n\s*//\s*(?:Properties|Methods)|\n\}})", re.DOTALL)
        match = pattern_class.search(dump_text)
        
    if not match:
        return []
        
    body = match.group(1)
    return extract_fields_from_struct_text(body)


def generate_csharp_class(binding_name: str, fields: List[Tuple[str, str, str]]) -> str:
    """Gera o código C# da classe de binding gerada."""
    class_name = f"Generated{binding_name}"
    
    lines = [
        "// <auto-generated>",
        "//   Gerado automaticamente por Tools/generate_bindings.py a partir do dump.cs oficial.",
        "//   Não edite este arquivo manualmente. Em atualizações do Dofus, reexecute o script.",
        "// </auto-generated>",
        "",
        "using System;",
        "using UnityEngine;",
        "using UnityEngine.UIElements;",
        "",
        "namespace Jondo.UI.Generated",
        "{",
        f"    public class {class_name}",
        "    {",
        "        public VisualElement Root { get; private set; }",
        "",
        "        // --- Elementos Fortemente Tipados da Interface ---",
    ]
    
    for raw_type, mapped_type, name in fields:
        lines.append(f"        public {mapped_type} {name} {{ get; private set; }}")
        
    lines.extend([
        "",
        "        /// <summary>",
        "        /// Vincula todos os elementos a partir da raiz da UI (UXML instanciado).",
        "        /// </summary>",
        "        public void Bind(VisualElement root)",
        "        {",
        "            Root = root;",
        "            if (root == null) return;",
        "",
    ])
    
    for raw_type, mapped_type, name in fields:
        if mapped_type == "VisualElement":
            lines.append(f'            {name} = root.Q("{name}");')
        else:
            lines.append(f'            {name} = root.Q<{mapped_type}>("{name}");')
            
    lines.extend([
        "        }",
        "    }",
        "}",
        ""
    ])
    
    return "\r\n".join(lines)


def run_generator(dump_path: str, output_dir: str, target_bindings: List[str] = None) -> Dict[str, int]:
    """Executa a geração de bindings a partir do dump.cs para o diretório de destino."""
    if target_bindings is None:
        target_bindings = DEFAULT_TARGET_BINDINGS
        
    if not os.path.exists(dump_path):
        raise FileNotFoundError(f"Arquivo dump.cs não encontrado em: {dump_path}")
        
    os.makedirs(output_dir, exist_ok=True)
    
    print(f"[*] Lendo {dump_path}...")
    with open(dump_path, "r", encoding="utf-8", errors="ignore") as f:
        dump_text = f.read()
        
    results = {}
    print(f"[*] Gerando bindings para {len(target_bindings)} componentes...")
    for name in target_bindings:
        fields = parse_binding_from_dump(dump_text, name)
        if not fields:
            print(f"    [!] Aviso: {name} não encontrado no dump.cs!")
            results[name] = 0
            continue
            
        csharp_code = generate_csharp_class(name, fields)
        out_file = os.path.join(output_dir, f"Generated{name}.cs")
        with open(out_file, "w", encoding="utf-8") as f:
            f.write(csharp_code)
            
        print(f"    [OK] {name}: {len(fields)} campos mapeados -> {out_file}")
        results[name] = len(fields)
        
    return results


if __name__ == "__main__":
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    default_dump = os.path.join(repo_root, "Decompiled", "dump.cs")
    default_output = os.path.join(repo_root, "UnityProject", "Assets", "Generated", "UI")
    
    dump_arg = sys.argv[1] if len(sys.argv) > 1 else default_dump
    output_arg = sys.argv[2] if len(sys.argv) > 2 else default_output
    
    print("======================================================================")
    print("  DOFUS UNITY AUTOMATED BINDING GENERATOR (Pilar 2)")
    print("======================================================================")
    results = run_generator(dump_arg, output_arg)
    print(f"\n[SUCESSO] Total de bindings gerados: {sum(1 for v in results.values() if v > 0)}/{len(results)}")

