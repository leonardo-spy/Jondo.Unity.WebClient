def load_transcribed(type_name):
    """Load transcribed JSON for a given type."""
    safe_name = type_name.replace('.', '_').replace('<', '_').replace('>', '_')
    path = TRANSCRIBED_DIR / f"{safe_name}.json"
    if not path.exists():
        path = TRANSCRIBED_DIR / f"{type_name}.json"
    if not path.exists():
        raise FileNotFoundError(f"Transcribed file not found for {type_name} at {path}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


