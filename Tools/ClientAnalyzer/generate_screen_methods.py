def extract_all_screen_classes():
    """Extract all screen classes from Core.UILogic and Core.UI (excluding Bindings)."""
    classes = []
    if not DUMP_CS.exists():
        return classes

    current_ns = ""
    current_cls = ""
    current_type_idx = 0
    in_target_ns = False
    methods_count = 0

    with open(DUMP_CS, "r", encoding="utf-8") as f:
        for line in f:
            if line.startswith("// Namespace: "):
                ns = line.replace("// Namespace: ", "").strip()
                current_ns = ns
                in_target_ns = (
                    (ns.startswith("Core.UILogic") or ns.startswith("Core.UI"))
                    and not (ns.startswith("Core.UILogic.Bindings") or ns.startswith("Core.UI.Bindings"))
                )
            elif in_target_ns and ("class " in line or "struct " in line or "interface " in line):
                if current_cls and current_type_idx > 0:
                    classes.append({
                        "namespace": current_ns,
                        "name": current_cls,
                        "typeDef": current_type_idx,
                        "methodsCount": methods_count
                    })
                m_cls = re.search(r'(?:public|private|internal|protected)?\s*(?:sealed|abstract|static)?\s*(?:class|struct|interface)\s+([\w<>_]+)', line)
                current_cls = m_cls.group(1) if m_cls else ""
                m_type = re.search(r'TypeDefIndex:\s*(\d+)', line)
                current_type_idx = int(m_type.group(1)) if m_type else 0
                methods_count = 0
            elif in_target_ns and "// RVA: " in line:
                methods_count += 1

        if current_cls and current_type_idx > 0:
            classes.append({
                "namespace": current_ns,
                "name": current_cls,
                "typeDef": current_type_idx,
                "methodsCount": methods_count
            })

    seen = set()
    dedup = []
    for c in classes:
        key = (c["namespace"], c["name"])
        if key not in seen:
            seen.add(key)
            dedup.append(c)

    return dedup


