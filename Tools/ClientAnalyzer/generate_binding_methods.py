def extract_all_binding_classes():
    """Extract all 757 binding classes from dump.cs."""
    classes = []
    if not DUMP_CS.exists():
        return classes

    current_ns = ""
    current_cls = ""
    current_type_idx = 0
    in_target_ns = False
    methods_count = 0
    fields = []

    with open(DUMP_CS, "r", encoding="utf-8") as f:
        for line in f:
            if line.startswith("// Namespace: "):
                ns = line.replace("// Namespace: ", "").strip()
                current_ns = ns
                in_target_ns = ns.startswith("Core.UI.Bindings") or ns.startswith("Core.UILogic.Bindings")
            elif in_target_ns and ("class " in line or "struct " in line or "interface " in line):
                # Save previous class if exists
                if current_cls and current_type_idx > 0:
                    classes.append({
                        "namespace": current_ns,
                        "name": current_cls,
                        "typeDef": current_type_idx,
                        "methodsCount": methods_count,
                        "fields": fields
                    })
                m_cls = re.search(r'(?:public|private|internal|protected)?\s*(?:sealed|abstract|static)?\s*(?:class|struct|interface)\s+([\w<>_]+)', line)
                current_cls = m_cls.group(1) if m_cls else ""
                m_type = re.search(r'TypeDefIndex:\s*(\d+)', line)
                current_type_idx = int(m_type.group(1)) if m_type else 0
                methods_count = 0
                fields = []
            elif in_target_ns and "// RVA: " in line:
                methods_count += 1
            elif in_target_ns and line.strip().startswith("private ") or line.strip().startswith("public "):
                # Field inspection
                parts = line.strip().split()
                if len(parts) >= 3 and parts[-1].startswith(";"):
                    fname = parts[-1].rstrip(";")
                    fields.append(fname)

        if current_cls and current_type_idx > 0:
            classes.append({
                "namespace": current_ns,
                "name": current_cls,
                "typeDef": current_type_idx,
                "methodsCount": methods_count,
                "fields": fields
            })

    # Deduplicate by (namespace, name)
    seen = set()
    dedup = []
    for c in classes:
        key = (c["namespace"], c["name"])
        if key not in seen:
            seen.add(key)
            dedup.append(c)

    return dedup


